//! Builds hzeller's driver when the `link` feature is on (docs/adr/0009).
//! Without `link`, there is nothing to build.

fn main() {
    #[cfg(feature = "link")]
    driver::build();
}

#[cfg(feature = "link")]
mod driver {
    use std::env;
    use std::fmt::Write as _;
    use std::path::{Path, PathBuf};

    /// Sources from `OBJECTS` in the pinned `lib/Makefile`. Check this list
    /// again at each submodule update (docs/adr/0009).
    const CXX_SOURCES: &[&str] = &[
        "gpio.cc",
        "led-matrix.cc",
        "options-initialize.cc",
        "framebuffer.cc",
        "thread.cc",
        "bdf-font.cc",
        "graphics.cc",
        "led-matrix-c.cc",
        "pixel-mapper.cc",
        "multiplex-mappers.cc",
        "frame-sequence.cc",
        "content-streamer.cc",
        "content-streamer-c.cc",
        "frame-sequence-c.cc",
        "rp1/rp1_pio_backend.cc",
        "rp1/rp1_rio_backend.cc",
    ];
    const C_SOURCES: &[&str] = &["hardware-mapping.c", "rp1/rp1_pio_support.c"];

    /// Expected C layouts on 32-bit targets (the Pi), as `(name, bytes)`. This
    /// one table supplies two checks:
    /// - `-DLAYOUT_*` for `src/layout_check.c`, against the real header.
    /// - `$OUT_DIR/layout.rs` for `src/ffi.rs`, against our Rust structs.
    const LAYOUT_32: &[(&str, usize)] = &[
        ("COLOR_SIZE", 3),
        ("OPTIONS_SIZE", 72),
        ("OPTIONS_HARDWARE_MAPPING", 0),
        ("OPTIONS_ROWS", 4),
        ("OPTIONS_COLS", 8),
        ("OPTIONS_CHAIN_LENGTH", 12),
        ("OPTIONS_PARALLEL", 16),
        ("OPTIONS_PWM_BITS", 20),
        ("OPTIONS_PWM_LSB_NANOSECONDS", 24),
        ("OPTIONS_PWM_DITHER_BITS", 28),
        ("OPTIONS_BRIGHTNESS", 32),
        ("OPTIONS_SCAN_MODE", 36),
        ("OPTIONS_ROW_ADDRESS_TYPE", 40),
        ("OPTIONS_MULTIPLEXING", 44),
        ("OPTIONS_DISABLE_HARDWARE_PULSING", 48),
        ("OPTIONS_SHOW_REFRESH_RATE", 49),
        ("OPTIONS_INVERSE_COLORS", 50),
        ("OPTIONS_LED_RGB_SEQUENCE", 52),
        ("OPTIONS_PIXEL_MAPPER_CONFIG", 56),
        ("OPTIONS_PANEL_TYPE", 60),
        ("OPTIONS_LIMIT_REFRESH_RATE_HZ", 64),
        ("OPTIONS_DISABLE_BUSY_WAITING", 68),
    ];

    /// The Makefile's default. We set the mapping at runtime.
    const DEFAULT_HARDWARE: &str = "\"regular\"";

    pub fn build() {
        let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("set by cargo"));
        let root = manifest.join("../../vendor/rpi-rgb-led-matrix");
        let lib = root.join("lib");
        let include = root.join("include");

        assert!(
            lib.join("led-matrix-c.cc").is_file(),
            "hzeller's driver source is missing from {}.\n\
             Run `git submodule update --init` and build again.",
            root.display()
        );

        let rp1_includes = [
            lib.join("rp1/rp1_pio_vendor/piolib/include"),
            lib.join("rp1/rp1_pio_vendor/include"),
        ];

        // Build C++ first. Its static library uses symbols from the C library.
        // Cargo gives static libraries to the linker in this order.
        let mut cxx = base(&include, &rp1_includes);
        cxx.cpp(true).flag("-fno-exceptions").flag("-std=c++11");
        cxx.files(CXX_SOURCES.iter().map(|s| lib.join(s)));
        cxx.compile("rgbmatrix");

        let mut c = base(&include, &rp1_includes);
        c.files(C_SOURCES.iter().map(|s| lib.join(s)));
        layout_check(&mut c, &manifest);
        c.compile("rgbmatrix_c");

        for system_lib in ["pthread", "rt", "m"] {
            println!("cargo:rustc-link-lib={system_lib}");
        }
        println!("cargo:rerun-if-changed={}", lib.display());
        println!("cargo:rerun-if-changed={}", include.display());
    }

    /// Add `src/layout_check.c` to `build` with the expected layout, and write
    /// the same numbers to `$OUT_DIR/layout.rs` for the Rust side.
    fn layout_check(build: &mut cc::Build, manifest: &Path) {
        let pointer_width = env::var("CARGO_CFG_TARGET_POINTER_WIDTH").unwrap_or_default();
        assert!(
            pointer_width == "32",
            "the FFI layout table only covers 32-bit targets (the Pi); \
             target pointer width is {pointer_width}"
        );
        let mut rust = String::from("// Generated by build.rs from LAYOUT_32.\n");
        for (name, value) in LAYOUT_32 {
            build.define(&format!("LAYOUT_{name}"), value.to_string().as_str());
            writeln!(rust, "pub const {name}: usize = {value};").expect("write to String");
        }
        let out = PathBuf::from(env::var_os("OUT_DIR").expect("set by cargo"));
        std::fs::write(out.join("layout.rs"), rust).expect("write layout.rs");

        let check = manifest.join("src/layout_check.c");
        println!("cargo:rerun-if-changed={}", check.display());
        build.file(check);
    }

    /// Settings shared by the C and C++ builds, mirroring `lib/Makefile`
    /// minus `-march=native` and LTO (we cross-compile).
    fn base(include: &Path, extra_includes: &[PathBuf]) -> cc::Build {
        let mut b = cc::Build::new();
        b.include(include)
            .includes(extra_includes)
            .define("DEFAULT_HARDWARE", DEFAULT_HARDWARE)
            .opt_level(3)
            // Vendored code. Upstream owns its warnings.
            .warnings(false);
        if env::var("TARGET").is_ok_and(|t| t.starts_with("arm-unknown-linux-gnueabihf")) {
            // ARM1176JZF-S (Pi Zero W). Without this, zig selects a generic CPU.
            b.flag("-mcpu=arm1176jzf_s");
        }
        b
    }
}
